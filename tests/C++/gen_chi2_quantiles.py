#!/usr/bin/env python3
"""Writes chi2_quantiles.inc: chi-square quantiles from SciPy, the reference
test_math.cpp checks InverseChiSquareCDF2 against.

Rows are {k, x, q} with q the quantile of k degrees of freedom at x, all as
C99 hex floats so that nothing is lost in printing. The upper half comes from
the survival function at 1 - x (exact in doubles for x >= 0.5), which keeps its
precision in the tail where 1 - x is tiny.

    python3 gen_chi2_quantiles.py > chi2_quantiles.inc
"""
import scipy
from scipy.stats import chi2

KS = list(range(1, 101)) + [120, 150, 200, 250, 300, 500, 1000, 10**4, 10**5, 10**6]
XS = [1e-300, 1e-100, 1e-12, 1e-6, 1e-3, 0.01, 0.05, 0.1, 0.25, 0.5, 0.75, 0.9, 0.95,
      0.99, 0.995, 0.999, 0.9999, 0.99999, 1 - 1e-8, 1 - 1e-12, 1 - 2**-53]

print(f"// Generated by gen_chi2_quantiles.py with SciPy {scipy.__version__}; do not edit.")
for k in KS:
    for x in XS:
        q = chi2.ppf(x, k) if x <= 0.5 else chi2.isf(1.0 - x, k)
        if q > 0.0:
            print(f"{{{k}, {x.hex()}, {float(q).hex()}}},")
